using System;
using System.IO;
using System.Linq;
using System.Net.Mail;
using System.Web.Http.Results;
using BMF_WebSite.Controllers;
using BMF_WebSite.Models;

internal static class Checks
{
    private static void Assert(bool condition, string description)
    {
        if (!condition) throw new Exception(description);
        Console.WriteLine("PASS: " + description);
    }

    private static void Main(string[] args)
    {
        System.Net.ServicePointManager.SecurityProtocol = System.Net.SecurityProtocolType.Tls12;
        if (args[0] == "--live" || args[0] == "--send-test")
        {
            var site = Path.GetFullPath(args[1]);
            var domain = AppDomain.CreateDomain("BMF OAuth verification", null, new AppDomainSetup
            {
                ApplicationBase = site,
                PrivateBinPath = "bin",
                ConfigurationFile = Path.Combine(site, "Web.config")
            });
            try
            {
                var check = (LiveOAuthCheck)domain.CreateInstanceFromAndUnwrap(typeof(LiveOAuthCheck).Assembly.Location, typeof(LiveOAuthCheck).FullName);
                if (args[0] == "--send-test")
                    check.SendTest(args[2]);
                else
                    check.Run();
            }
            finally { AppDomain.Unload(domain); }
            return;
        }
        var html = PasswordEmailService.Render("<script>alert(1)</script>", "member@example.com", "<&\" {{FullName}}");
        Assert(!html.Contains("<script>") && html.Contains("&lt;script&gt;"), "Member names are HTML encoded");
        Assert(html.Contains("&lt;&amp;&quot; {{FullName}}"), "Password characters and literal template tokens are preserved");
        Assert(PasswordEmailService.Render(null, "member@example.com", "demo").Contains("Dear BMF member,"), "Missing profiles use a friendly fallback");

        using (var message = PasswordEmailService.CreateMessage("Test Member", "member@example.com", "sample-password"))
        {
            Assert(message.To.Count == 1 && message.To[0].Address == "member@example.com" && message.CC.Count == 0 && message.Bcc.Count == 0,
                "Account details go only to the member");
            Assert(message.From.Address == "bahrainmotorfederation@outlook.com", "Sender uses the configured Outlook mailbox");
            Assert(!message.IsBodyHtml && message.Body.Contains("sample-password"), "Email includes a plain text fallback");
            Assert(message.AlternateViews.Count == 1 && message.AlternateViews[0].ContentType.MediaType == "text/html", "Email includes the HTML design");
            var logo = message.AlternateViews[0].LinkedResources.Single();
            Assert(logo.ContentId == "bmf-logo" && logo.ContentStream.Length > 0, "BMF logo is embedded for email clients");
            using (var header = new System.Drawing.Bitmap(logo.ContentStream))
            {
                Assert(header.Width == 1200 && header.Height == 340, "The embedded image covers the whole logo header");
                Assert(!System.Drawing.Image.IsAlphaPixelFormat(header.PixelFormat), "The email logo header has no transparency");
                Assert(header.GetPixel(0, 0).ToArgb() == System.Drawing.Color.White.ToArgb()
                    && header.GetPixel(header.Width - 1, header.Height - 1).ToArgb() == System.Drawing.Color.White.ToArgb(),
                    "White padding is baked into the actual email attachment");
            }
        }

        using (var controller = new UserAccountController())
        {
            foreach (var user in new[] { null, new ClsUser(), new ClsUser { Email_Address = " " }, new ClsUser { Email_Address = "not-an-email" },
                new ClsUser { Email_Address = "member@example.com\r\nBcc: other@example.com" } })
                Assert(((NegotiatedContentResult<string>)controller.SendAccountPassword(user).GetAwaiter().GetResult()).StatusCode == System.Net.HttpStatusCode.BadRequest,
                    "Invalid request is rejected before a database query");
            controller.ModelState.AddModelError("Email_Address", "Invalid JSON value");
            Assert(((NegotiatedContentResult<string>)controller.SendAccountPassword(new ClsUser { Email_Address = "member@example.com" }).GetAwaiter().GetResult())
                .StatusCode == System.Net.HttpStatusCode.BadRequest, "Invalid model state is rejected");
        }

        RecoveryApiChecks.Run();

        // Test configuration points to a loopback fixture. Never send these messages externally.
        try
        {
            // Only trust the exact ephemeral certificate generated by the local test fixture.
            var certificate = new System.Security.Cryptography.X509Certificates.X509Certificate2(args[1]);
            System.Net.ServicePointManager.ServerCertificateValidationCallback = (sender, cert, chain, errors) => cert.GetCertHashString() == certificate.GetCertHashString();
            PasswordEmailService.SendWithAccessTokenAsync("Test Member", "member@example.com", "sample-password", "fixture-token").GetAwaiter().GetResult();
            Assert(true, "SMTP send succeeds over STARTTLS using XOAUTH2");
            try
            {
                PasswordEmailService.SendWithAccessTokenAsync("Test Member", "member@example.com", "sample-password", "fixture-token").GetAwaiter().GetResult();
                throw new Exception("Expected the fixture to reject authentication.");
            }
            catch (MailKit.Security.AuthenticationException)
            {
                Assert(true, "SMTP authentication failures propagate instead of reporting Sent");
            }
            PasswordEmailService.SendWithAccessTokenAsync("Test Member", "member@example.com", "sample-password", "fixture-token").GetAwaiter().GetResult();
            Assert(true, "A disconnect failure after SMTP acceptance does not incorrectly report a failed send");
        }
        finally
        {
            System.Net.ServicePointManager.ServerCertificateValidationCallback = null;
        }

        var preview = PasswordEmailService.Render("Ahmed Ali", "ahmed.ali@example.com", "BMF-Demo!2026");
        using (var message = PasswordEmailService.CreateMessage("Ahmed Ali", "ahmed.ali@example.com", "BMF-Demo!2026"))
        using (var memory = new MemoryStream())
        {
            var logo = message.AlternateViews[0].LinkedResources.Single().ContentStream;
            logo.CopyTo(memory);
            preview = preview.Replace("cid:bmf-logo", "data:image/png;base64," + Convert.ToBase64String(memory.ToArray()));
        }
        File.WriteAllText(args[0], preview, new System.Text.UTF8Encoding(false));
        Console.WriteLine("Generated design preview with fictional account details.");
    }
}

public sealed class LiveOAuthCheck : MarshalByRefObject
{
    public void SendTest(string recipient)
    {
        System.Net.ServicePointManager.SecurityProtocol = System.Net.SecurityProtocolType.Tls12;
        var token = OutlookOAuthTokenProvider.GetAccessTokenAsync().GetAwaiter().GetResult();
        using (var message = PasswordEmailService.CreateMessage("BMF test recipient", recipient, "BMF-Demo!2026 (test only)"))
        using (var mimeMessage = MimeKit.MimeMessage.CreateFromMailMessage(message))
        using (var client = new MailKit.Net.Smtp.SmtpClient())
        {
            mimeMessage.Subject = "[TEST] Your BMF App account details";
            client.Timeout = 30000;
            client.SslProtocols = System.Security.Authentication.SslProtocols.Tls12;
            client.Connect(System.Configuration.ConfigurationManager.AppSettings["PasswordEmail.SmtpHost"],
                int.Parse(System.Configuration.ConfigurationManager.AppSettings["PasswordEmail.SmtpPort"]), MailKit.Security.SecureSocketOptions.StartTls);
            client.Authenticate(new MailKit.Security.SaslMechanismOAuth2(message.From.Address, token));
            var response = client.Send(mimeMessage);
            Console.WriteLine("TEST EMAIL ACCEPTED: " + recipient);
            Console.WriteLine("Subject: " + mimeMessage.Subject);
            Console.WriteLine("Message-ID: " + mimeMessage.MessageId);
            Console.WriteLine("SMTP response: " + response);
            client.Disconnect(true);
        }
    }

    public void Run()
    {
        System.Net.ServicePointManager.SecurityProtocol = System.Net.SecurityProtocolType.Tls12;
        var token = OutlookOAuthTokenProvider.GetAccessTokenAsync().GetAwaiter().GetResult();
        if (token != OutlookOAuthTokenProvider.GetAccessTokenAsync().GetAwaiter().GetResult())
            throw new Exception("The access token was not cached.");
        using (var client = new MailKit.Net.Smtp.SmtpClient())
        {
            client.SslProtocols = System.Security.Authentication.SslProtocols.Tls12;
            client.Connect("smtp-mail.outlook.com", 587, MailKit.Security.SecureSocketOptions.StartTls);
            client.Authenticate(new MailKit.Security.SaslMechanismOAuth2("bahrainmotorfederation@outlook.com", token));
            client.Disconnect(true);
        }
        Console.WriteLine("PASS: Live .NET token renewal, token cache, and Outlook XOAUTH2 authentication. No email sent.");
    }
}
